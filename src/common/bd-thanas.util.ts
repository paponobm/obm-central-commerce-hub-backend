function normalize(text: string): string {
  return text.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, '');
}

// Scoped to one district's own thanas only (see the name-collision note
// above) — never a flat search across all 544, which could silently
// assign the wrong one.
export function detectThana(address: string | null | undefined, district: string | null | undefined): string | null {
  if (!address || !district) return null;
  const norm = normalize(address);
  if (!norm) return null;
  const candidates = BD_THANAS.filter((t) => t.district === district)
    .map((t) => ({ name: t.name, norm: normalize(t.name) }))
    .filter((t) => t.norm.length > 0)
    .sort((a, b) => b.norm.length - a.norm.length);
  for (const c of candidates) {
    if (norm.includes(c.norm)) return c.name;
  }
  return null;
}
